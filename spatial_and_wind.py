class SpatialAnalyzer:

    @staticmethod
    def calculate_distance(event: Event, target: Location) -> float:
        return round(
            haversine_km(
                event.lat,
                event.lon,
                target.lat,
                target.lon
            ),
            3,
        )

    @staticmethod
    def calculate_bearing(event: Event, target: Location) -> float:
        return round(
            bearing_deg(
                event.lat,
                event.lon,
                target.lat,
                target.lon
            ) % 360,
            2,
        )

    @staticmethod
    def calculate_proximity_score(
        distance_km: float,
        max_distance_km: float = 500.0,
    ) -> float:

        if distance_km < 0:
            raise ValueError("distance_km cannot be negative.")

        if max_distance_km <= 0:
            raise ValueError(
                "max_distance_km must be greater than zero."
            )

        score = 1.0 - (distance_km / max_distance_km)

        return round(
            max(0.0, min(1.0, score)),
            3
        )

    def analyze_proximity(
        self,
        event: Event,
        target: Location,
        max_distance_km: float = 500.0,
    ) -> SpatialEvidence:

        distance = self.calculate_distance(event, target)
        bearing = self.calculate_bearing(event, target)
        proximity = self.calculate_proximity_score(
            distance,
            max_distance_km
        )

        return {
            "event_id": event.id,
            "target_id": target.id,
            "distance_km": distance,
            "proximity_score": proximity,
            "bearing_deg": bearing,
        }


