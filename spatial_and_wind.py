class WindAnalyzer:
    "Analyzes wind effects on environmental events."

    @staticmethod
    def calculate_wind_alignment(
        bearing_to_target_deg: float,
        wind_direction_deg: float,
        tolerance_deg: float = 45
    ) -> Tuple[float, bool]:

        # Wind blows TO this direction (add 180 to FROM direction)
        wind_towards = (wind_direction_deg + 180) % 360

        # Calculate angular difference
        diff = abs(wind_towards - bearing_to_target_deg)
        if diff > 180:
            diff = 360 - diff

        # Alignment score: 1.0 at 0°, 0.0 at 180°
        alignment_score = max(0, 1 - (diff / 180))

        # Is aligned?
        is_aligned = diff <= tolerance_deg

        return alignment_score, is_aligned

    @staticmethod
    def analyze_wind(
        event: Event,
        target: Location,
        wind_direction_deg: float,
        wind_speed_ms: float = 5.0,
    ) -> WindAnalysis:
        bearing = bearing_deg(event.lat, event.lon, target.lat, target.lon)
        alignment, is_downwind = WindAnalyzer.calculate_wind_alignment(
            bearing, wind_direction_deg
        )

        return {
            "wind_direction_deg": wind_direction_deg,
            "wind_speed_ms": wind_speed_ms,
            "bearing_to_target_deg": bearing,
            "alignment_score": alignment,
            "is_downwind": is_downwind,
        }

